  /* LANGUE PAR DEFAUT : L'ANGLAIS.
     Les publicites sont en anglais et touchent le monde entier : la premiere
     chose qu'un visiteur voit doit etre dans la meme langue que l'annonce
     qui l'a amene. On ne devine plus la langue du navigateur — un visiteur
     francais qui clique sur une annonce anglaise verrait sinon une page
     francaise, sans rapport avec ce qu'il vient de lire.
     Des que la personne choisit une langue, ce choix est retenu et prime. */
  function langue() {
    try {
      var c = localStorage.getItem('skillora_lang');
      if (c && D[c]) return c;
    } catch (e) {}
    return 'en';
  }

  function appliquer() {
    var lg = langue(), d = D[lg] || D.fr;
    document.documentElement.lang = lg;
    document.querySelectorAll('[data-t]').forEach(function (el) {
      var v = d[el.getAttribute('data-t')];
      if (v != null) el.innerHTML = v;
    });
    document.querySelectorAll('[data-tph]').forEach(function (el) {
      var v = d[el.getAttribute('data-tph')];
      if (v != null) el.placeholder = v;
    });
    document.querySelectorAll('#skLangs button').forEach(function (b) {
      b.classList.toggle('on', b.getAttribute('data-l') === lg);
    });
  }

  global.skLandingLang = function (l) {
    try { localStorage.setItem('skillora_lang', l); } catch (e) {}
    appliquer();
  };
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', appliquer);
  else appliquer();
